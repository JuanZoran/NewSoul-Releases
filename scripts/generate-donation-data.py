#!/usr/bin/env python3
"""Generate code-owned, lossless image bytes; --check rejects stale build inputs."""
import base64
import hashlib
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'app/src/main/java/dev/local/newsoul/DonationImageData.java'
lines = ['// Generated by scripts/generate-donation-data.py; do not edit.',
         'package dev.local.newsoul;', '', 'final class DonationImageData {',
         '    private DonationImageData() {}',
         '    static byte[] read(int index) {',
         '        switch (index) {',
         '            case 0: return wechat();',
         '            case 1: return alipay();',
         '            default: throw new IllegalArgumentException("Unknown payment code");',
         '        }', '    }']
for name, extension in [('wechat', 'png'), ('alipay', 'jpg')]:
    raw = (ROOT / f'app/donation-source/donation_{name}.{extension}').read_bytes()
    encoded = base64.b64encode(raw).decode('ascii')
    assert base64.b64decode(encoded) == raw
    lines += [f'    // Original SHA-256: {hashlib.sha256(raw).hexdigest()}',
              f'    private static byte[] {name}() {{',
              '        StringBuilder data = new StringBuilder();']
    # Separate appends prevent javac folding into a >64 KB constant.
    lines += [f'        data.append("{encoded[i:i+8192]}");' for i in range(0, len(encoded), 8192)]
    lines += ['        return java.util.Base64.getDecoder().decode(data.toString());', '    }']
lines += ['}', '']
result = '\n'.join(lines)
if '--check' in sys.argv:
    if not DEST.exists() or DEST.read_text() != result:
        sys.exit('Stale donation data; run python3 scripts/generate-donation-data.py')
    print('Donation image data matches original files')
else:
    DEST.write_text(result)
